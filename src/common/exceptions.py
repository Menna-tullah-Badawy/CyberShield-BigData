"""
Enterprise Custom Exceptions Hierarchy.
الهيكل الهرمي للاستثناءات البرمجية المخصصة لكافة طبقات النظام.
"""

# ==============================================================================
# 1. الكلاس الأساسي لجميع استثناءات المنصة (Base Exception)
# ==============================================================================
class CyberShieldException(Exception):
    """
    الكلاس الأساسي لجميع الأخطاء المخصصة داخل منصة CyberShield.
    يضمن تتبع رسائل الخطأ بدقة وسهولة فلترتها.
    """
    def __init__(self, message: str):
        # استدعاء مشيد الفئة الأب وتمرير الرسالة
        super().__init__(message)
        # حفظ نص الرسالة كخاصية مستقلة
        self.message = message

    def __str__(self):
        # صياغة طباعة الخطأ بشكل مقروء
        return f"[CyberShield Error] {self.message}"


# ==============================================================================
# 2. استثناءات خطوط تدفق وسحب البيانات (Data Ingestion & Pipeline Exceptions)
# ==============================================================================
class DataPipelineError(CyberShieldException):
    """يتم إطلاقه عند فشل استيراد، قراءة، أو تحويل تدفقات البيانات."""
    pass


class IngestionFileNotFoundError(DataPipelineError):
    """يتم إطلاقه عند عدم العثور على ملفات الـ PCAP أو الـ CSV الخام."""
    pass


# ==============================================================================
# 3. استثناءات بوابات فحص الجودة والتنظيف (Data Quality & Cleaning Exceptions)
# ==============================================================================
class DataQualityError(CyberShieldException):
    """يتم إطلاقه عند فشل فحص جودة البيانات أو انتهاك شروط الـ Schema."""
    pass


class SchemaValidationError(DataQualityError):
    """يتم إطلاقه عند عدم تطابق هيكل البيانات الفعلي مع المخطط المتوقع."""
    pass


class ExcessiveMissingDataError(DataQualityError):
    """يتم إطلاقه إذا تجاوزت نسبة القيم المفقودة الحدود المسموح بها برمجياً."""
    pass


# ==============================================================================
# 4. استثناءات تدريب النماذج والذكاء الاصطناعي (Model & Training Exceptions)
# ==============================================================================
class ModelTrainingError(CyberShieldException):
    """يتم إطلاقه عند حدوث انهيار أثناء تدريب أو تقييم نماذج التعلم الآلي."""
    pass


class ModelNotFoundError(ModelTrainingError):
    """يتم إطلاقه عند محاولة استدعاء أو تقييم نموذج غير محفوظ على القرص."""
    pass


# ==============================================================================
# 5. استثناءات المراقبة وانحراف البيانات (Monitoring & Drift Exceptions)
# ==============================================================================
class DriftDetectionError(CyberShieldException):
    """يتم إطلاقه عند حدوث خطأ رياضي أثناء حساب اختبارات الانحراف الإحصائي (KS-Test)."""
    pass